import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages, playerStats, scenario } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemPrompt = `You are a dark fantasy RPG Game Master running a text-based dungeon crawler. You narrate in second person ("You enter the chamber..."). Keep responses under 150 words.

Player stats: HP ${playerStats.hp}/${playerStats.maxHp}, ATK ${playerStats.attack}, DEF ${playerStats.defense}, Gold ${playerStats.gold}, Level ${playerStats.level}

Rules:
- Narrate the outcome of the player's action dramatically
- Include combat damage numbers when fighting (e.g. "You deal 15 damage, taking 8 in return")
- Return a JSON block at the END of your narrative with mechanical effects:
\`\`\`json
{"hpChange": number, "goldChange": number, "xpGain": number, "outcome": "success"|"failure"|"neutral"}
\`\`\`
- hpChange can be negative (damage) or positive (healing)
- Be fair but dangerous. Death should be possible.
- After the outcome, suggest 3-4 new choices as a JSON array:
\`\`\`choices
["Choice 1", "Choice 2", "Choice 3"]
\`\`\``;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limited. Try again shortly." }), {
          status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted." }), {
          status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI error:", response.status, t);
      throw new Error("AI gateway error");
    }

    const data = await response.json();
    const content = data.choices?.[0]?.message?.content || "";

    return new Response(JSON.stringify({ content }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (e) {
    console.error("game-master error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
